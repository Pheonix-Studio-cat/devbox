// Inlines the built bundle into a single self-contained index.html at the
// repository root, and commits it alongside the source.
//
// GitHub Pages has two modes. "GitHub Actions" runs .github/workflows/pages.yml
// and publishes dist/. "Deploy from a branch" ignores the build entirely and
// serves the repository as it stands — which used to mean the development page
// and its TypeScript entry, neither of which a browser can run, so the site
// came up blank. A prebuilt root page makes both modes serve the real app.
//
// Everything is inlined, so the file works from any path and needs no base URL.
import { readFile, writeFile, readdir } from "node:fs/promises";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const dist = join(root, "dist");

const findAsset = async (extension) => {
  const files = await readdir(join(dist, "assets"));
  const match = files.find((name) => name.endsWith(extension));
  if (!match) throw new Error(`No ${extension} bundle in dist/assets — run vite build first.`);
  return readFile(join(dist, "assets", match), "utf8");
};

const [css, js, favicon, source] = await Promise.all([
  findAsset(".css"),
  findAsset(".js"),
  readFile(join(root, "public", "favicon.svg"), "utf8"),
  readFile(join(root, "app", "index.html"), "utf8"),
]);

const title = /<title>([^<]*)<\/title>/.exec(source)?.[1] ?? "Devbox";
const description = /name="description"\s+content="([^"]*)"/s.exec(source)?.[1] ?? "";

const page = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${title}</title>
    <meta name="description" content="${description}" />
    <meta name="color-scheme" content="dark light" />
    <link rel="icon" type="image/svg+xml" href="data:image/svg+xml;charset=utf-8,${encodeURIComponent(favicon)}" />
    <!--
      Generated by scripts/build-standalone.mjs — do not edit by hand.
      Regenerate with: npm run build
    -->
    <style>
${css}
    </style>
  </head>
  <body>
    <div id="app"></div>
    <script type="module">
${js}
    </script>
  </body>
</html>
`;

await writeFile(join(root, "index.html"), page);
const kilobytes = (Buffer.byteLength(page) / 1024).toFixed(1);
console.log(`index.html — ${kilobytes} kB self-contained`);
